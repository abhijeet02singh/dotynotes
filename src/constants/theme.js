/**
 * Resolves full semantic tokens for a specific color theme and appearance mode.
 */
export function getThemeTokens(colorThemeId = 'purple', isDark = false) {
  const normalizedTheme = THEME_PALETTES[colorThemeId] ? colorThemeId : 'purple';
  const modeKey = isDark ? 'dark' : 'light';
  return THEME_PALETTES[normalizedTheme][modeKey];
}

