/**
 * Universal color ID normalization map.
 * Ensures complete backward compatibility with existing notes saved with legacy
 * color IDs ('purple', 'rose', 'peach', 'green', etc.).
 */
export const COLOR_ALIASES = {
  purple: 'lavender',
  lavender: 'lavender',
  yellow: 'yellow',
  peach: 'yellow',
  orange: 'yellow',
  mint: 'mint',
  green: 'mint',
  rose: 'pink',
  pink: 'pink',
  blue: 'blue',
  teal: 'teal',
  sky: 'sky',
};

/**
 * Resolves a pastel color definition object by ID or alias safely.
 * Always returns a valid pastel object, falling back to 'lavender' (canonical purple) if unmapped.
 * NEVER Derives note color from the application theme!
 */
export function getPastelColor(colorId) {
  if (!colorId || typeof colorId !== 'string') {
    return PASTEL_NOTE_COLORS[4]; // Lavender (canonical purple)
  }
  const key = colorId.trim().toLowerCase();
  const normalized = COLOR_ALIASES[key] || key;
  return (
    PASTEL_NOTE_COLORS.find((p) => p.id === normalized || p.id === key) ||
    PASTEL_NOTE_COLORS[4]
  );
}

